<#
.SYNOPSIS
    Generates cross-platform auto-download package scripts (CMD/SH) and archives them.
.DESCRIPTION
    Creates get-with-aria2.cmd for Windows and get-with-aria2.sh for Linux/macOS,
    bundling aria2c/7z discovery and fallback download logic with split-zip extraction.
#>

[CmdletBinding()]
param(
    [Parameter(Mandatory = $true)]
    [string]$DistDir,

    [Parameter(Mandatory = $true)]
    [string[]]$PartsLines,

    [string]$ZipName = "isoautodl.zip"
)

$ErrorActionPreference = 'Stop'

function New-BAT {
    param([string]$destDir, [string[]]$PartsLines)
    $emitParts = @()
    foreach ($ln in $PartsLines) { $emitParts += '  echo(' + $ln }
    $lines = @(
      '@echo off',
      'setlocal ENABLEDELAYEDEXPANSION',
      '',
      'set "OutputDir=%~1"',
      'if not defined OutputDir set "OutputDir=."',
      '',
      'set "HERE=%~dp0"',
      'set "TMPDIR=%TEMP%\uup_parts_%RANDOM%%RANDOM%"',
      'mkdir "%TMPDIR%" >nul 2>&1',
      'set "LIST=%TMPDIR%\parts.txt"',
      'set "BIN=%HERE%bin"',
      'set "ARIA=%BIN%\aria2c.exe"',
      'set "SEVENZIP=%BIN%\7za.exe"',
      '',
      'set "ARCH=x64"',
      'if /i "%PROCESSOR_ARCHITECTURE%"=="ARM64" set "ARCH=arm64"',
      'if /i "%PROCESSOR_ARCHITEW6432%"=="ARM64" set "ARCH=arm64"',
      '',
      'if not exist "%ARIA%" (',
      '  where aria2c.exe >nul 2>&1 && (',
      '    for /f "delims=" %%I in (''where aria2c.exe'') do set "ARIA=%%I"',
      '  ) || (',
      '    echo aria2c not found. Downloading aria2 for Windows %ARCH%...',
      '    mkdir "%BIN%" >nul 2>&1',
      '    powershell -NoProfile -ExecutionPolicy Bypass -Command "[Net.ServicePointManager]::SecurityProtocol = [Net.SecurityProtocolType]::Tls12; $u = if (''%ARCH%'' -eq ''arm64'') { ''https://github.com/q3aql/aria2-builder/releases/download/v1.37.0/aria2-1.37.0-win-arm64-build1.zip'' } else { ''https://github.com/aria2/aria2/releases/download/release-1.37.0/aria2-1.37.0-win-64bit-build1.zip'' }; $z = Join-Path $env:TEMP ''aria2_dl.zip''; $x = Join-Path $env:TEMP ''aria2_ex''; Invoke-WebRequest -Uri $u -OutFile $z -UseBasicParsing; Expand-Archive $z $x -Force; $e = (Get-ChildItem $x -Filter ''aria2c.exe'' -Recurse | Select-Object -First 1).FullName; Copy-Item $e ''%BIN%\aria2c.exe'' -Force; Remove-Item $z, $x -Recurse -Force -ErrorAction SilentlyContinue"',
      '    if exist "%BIN%\aria2c.exe" set "ARIA=%BIN%\aria2c.exe"',
      '  )',
      ')',
      'if not exist "%ARIA%" (',
      '  echo ERROR: aria2c.exe not found and could not be downloaded automatically.',
      '  pause',
      '  exit /b 1',
      ')',
      '',
      'if not exist "%SEVENZIP%" (',
      '  if exist "%BIN%\7z.exe" (',
      '    set "SEVENZIP=%BIN%\7z.exe"',
      '  ) else if exist "%ProgramFiles%\7-Zip\7z.exe" (',
      '    set "SEVENZIP=%ProgramFiles%\7-Zip\7z.exe"',
      '  ) else if exist "%ProgramFiles(x86)%\7-Zip\7z.exe" (',
      '    set "SEVENZIP=%ProgramFiles(x86)%\7-Zip\7z.exe"',
      '  ) else (',
      '    where 7z.exe >nul 2>&1 && (',
      '      for /f "delims=" %%I in (''where 7z.exe'') do set "SEVENZIP=%%I"',
      '    ) || where 7za.exe >nul 2>&1 && (',
      '      for /f "delims=" %%I in (''where 7za.exe'') do set "SEVENZIP=%%I"',
      '    ) || (',
      '      echo 7-Zip not found. Downloading 7za for Windows %ARCH%...',
      '      mkdir "%BIN%" >nul 2>&1',
      '      powershell -NoProfile -ExecutionPolicy Bypass -Command "[Net.ServicePointManager]::SecurityProtocol = [Net.SecurityProtocolType]::Tls12; $u = if (''%ARCH%'' -eq ''arm64'') { ''https://www.7-zip.org/a/7zr.exe'' } else { ''https://www.7-zip.org/a/7za920.zip'' }; $t = Join-Path $env:TEMP ''7z_dl.zip''; Invoke-WebRequest -Uri $u -OutFile $t -UseBasicParsing; if ($u.EndsWith(''.zip'')) { Expand-Archive -Path $t -DestinationPath ''%BIN%'' -Force } else { Copy-Item $t -Destination ''%BIN%\7za.exe'' -Force }; Remove-Item $t -Force -ErrorAction SilentlyContinue"',
      '      if exist "%BIN%\7za.exe" set "SEVENZIP=%BIN%\7za.exe"',
      '      if exist "%BIN%\7z.exe" set "SEVENZIP=%BIN%\7z.exe"',
      '    )',
      '  )',
      ')',
      '',
      'rem Write embedded parts',
      '( '
    ) + $emitParts + @(
      ') > "%TMPDIR%\parts.txt"',
      '',
      'echo Starting download parts with Aria2',
      'echo.',
      '"%ARIA%" --input-file="%LIST%" --dir="%OutputDir%" --auto-file-renaming=false --allow-overwrite=true --continue=true --max-concurrent-downloads=16 --split=16 --min-split-size=1M --check-integrity=true --console-log-level=warn --summary-interval=30 --file-allocation=none',
      'if errorlevel 1 (echo ERROR: aria2 download failed & pause & exit /b 1)',
      '',
      'for /f "delims=" %%P in (''dir /b /a:-d "%OutputDir%\*.zip.001" 2^>nul'') do set "FIRST=%%P"',
      'if not defined FIRST (echo ERROR: No *.zip.001 found & pause & exit /b 1)',
      '',
      'if exist "%SEVENZIP%" (',
      '  echo Extracting ISO with 7z...',
      '  echo.',
      '  "%SEVENZIP%" x "%OutputDir%\%FIRST%" -o"%OutputDir%" -y -bsp1 -bso0',
      ') else (',
      '  echo 7-Zip not found; combining parts and extracting with Windows tools...',
      '  echo.',
      '  copy /b "%OutputDir%\*.zip.*" "%TMPDIR%\combined.zip" >nul',
      '  tar -xf "%TMPDIR%\combined.zip" -C "%OutputDir%" 2>nul || powershell -NoProfile -Command "Expand-Archive -Path ''%TMPDIR%\combined.zip'' -DestinationPath ''%OutputDir%'' -Force"',
      '  if exist "%TMPDIR%\combined.zip" del "%TMPDIR%\combined.zip" >nul 2>&1',
      ')',
      '',
      'for /f "delims=" %%I in (''dir /b /a:-d "%OutputDir%\*.ISO" 2^>nul'') do set "ISO=%%I"',
      'if not defined ISO (echo ERROR: ISO not found & pause & exit /b 1)',
      '',
      'echo ISO saved: %ISO%',
      'echo.',
      'echo Done',
      'echo.',
      'pause',
      'exit /b 0'
    )
    $path = Join-Path $destDir 'get-with-aria2.cmd'
    Set-Content -Path $path -Value ($lines -join "`r`n") -Encoding ASCII
}

function New-SH {
    param([string]$destDir, [string[]]$PartsLines)
    $lines = @(
      '#!/bin/sh',
      'set -eu',
      '',
      'SCRIPT_DIR=$(cd "$(dirname "$0")" && pwd)',
      'LAUNCH_DIR=$(pwd)',
      'TMPDIR="$LAUNCH_DIR/tmp_dir"',
      'LIST_FILE="$TMPDIR/parts.txt"',
      'ARIA2_BIN="$SCRIPT_DIR/bin/aria2c"',
      'ARIA2="$ARIA2_BIN"',
      'SEVEN_ZIP=""',
      'mkdir -p "$TMPDIR"',
      '',
      'OS="$(uname -s 2>/dev/null || echo Unknown)"',
      'ARCH="$(uname -m 2>/dev/null || echo Unknown)"',
      '',
      'for name in 7z 7zz 7zzs 7za; do',
      '  if command -v "$name" >/dev/null 2>&1; then',
      '    c=$(command -v "$name")',
      '    if "$c" i >/dev/null 2>&1; then',
      '      SEVEN_ZIP="$c"',
      '      echo "Using system 7z from: $SEVEN_ZIP"',
      '      break',
      '    fi',
      '  fi',
      'done',
      '',
      'if [ -z "$SEVEN_ZIP" ]; then',
      '  for name in 7zzs 7z 7za 7zz; do',
      '    c="$SCRIPT_DIR/bin/$name"',
      '    if [ -x "$c" ] && "$c" i >/dev/null 2>&1; then',
      '      SEVEN_ZIP="$c"',
      '      echo "Using bundled 7z from: $SEVEN_ZIP"',
      '      break',
      '    fi',
      '  done',
      'fi',
      '',
      'if [ -z "$SEVEN_ZIP" ]; then',
      '  mkdir -p "$SCRIPT_DIR/bin"',
      '  if [ "$OS" = "Linux" ]; then',
      '    Z_URL=""',
      '    case "$ARCH" in',
      '      x86_64)        Z_URL="https://www.7-zip.org/a/7z2408-linux-x64.tar.xz" ;;',
      '      aarch64|arm64) Z_URL="https://www.7-zip.org/a/7z2408-linux-arm64.tar.xz" ;;',
      '      arm*|armhf)    Z_URL="https://www.7-zip.org/a/7z2408-linux-arm.tar.xz" ;;',
      '    esac',
      '    if [ -n "$Z_URL" ]; then',
      '      echo "Downloading 7-Zip for Linux ($ARCH)..."',
      '      (curl -fsSL "$Z_URL" -o "$TMPDIR/7z.tar.xz" 2>/dev/null || wget -q "$Z_URL" -O "$TMPDIR/7z.tar.xz" 2>/dev/null || true)',
      '      if [ -f "$TMPDIR/7z.tar.xz" ]; then',
      '        tar -xf "$TMPDIR/7z.tar.xz" -C "$SCRIPT_DIR/bin" 2>/dev/null || true',
      '        chmod +x "$SCRIPT_DIR/bin/7zzs" "$SCRIPT_DIR/bin/7zz" 2>/dev/null || true',
      '        for b in "$SCRIPT_DIR/bin/7zzs" "$SCRIPT_DIR/bin/7zz"; do',
      '          if [ -x "$b" ] && "$b" i >/dev/null 2>&1; then',
      '            SEVEN_ZIP="$b"',
      '            break',
      '          fi',
      '        done',
      '      fi',
      '    fi',
      '  elif [ "$OS" = "Darwin" ]; then',
      '    echo "Downloading 7-Zip for macOS..."',
      '    (curl -fsSL "https://www.7-zip.org/a/7z2408-mac.tar.xz" -o "$TMPDIR/7z.tar.xz" 2>/dev/null || true)',
      '    if [ -f "$TMPDIR/7z.tar.xz" ]; then',
      '      tar -xf "$TMPDIR/7z.tar.xz" -C "$SCRIPT_DIR/bin" 2>/dev/null || true',
      '      chmod +x "$SCRIPT_DIR/bin/7zz" 2>/dev/null || true',
      '      if [ -x "$SCRIPT_DIR/bin/7zz" ] && "$SCRIPT_DIR/bin/7zz" i >/dev/null 2>&1; then',
      '        SEVEN_ZIP="$SCRIPT_DIR/bin/7zz"',
      '      fi',
      '    fi',
      '  fi',
      'fi',
      '',
      'if [ -x "$ARIA2" ] && "$ARIA2" --version >/dev/null 2>&1; then',
      '  :',
      'elif command -v aria2c >/dev/null 2>&1; then',
      '  ARIA2=$(command -v aria2c)',
      '  echo "Using system aria2c from: $ARIA2"',
      'else',
      '  mkdir -p "$SCRIPT_DIR/bin"',
      '  if [ "$OS" = "Linux" ]; then',
      '    A_URL=""',
      '    case "$ARCH" in',
      '      x86_64)        A_URL="https://github.com/q3aql/aria2-static-builds/releases/download/v1.37.0/aria2-1.37.0-linux-gnu-64bit-build1.tar.bz2" ;;',
      '      aarch64|arm64) A_URL="https://github.com/q3aql/aria2-static-builds/releases/download/v1.37.0/aria2-1.37.0-linux-gnu-arm64-build1.tar.bz2" ;;',
      '      arm*|armhf)    A_URL="https://github.com/q3aql/aria2-static-builds/releases/download/v1.37.0/aria2-1.37.0-linux-gnu-arm-build1.tar.bz2" ;;',
      '    esac',
      '    if [ -n "$A_URL" ]; then',
      '      echo "Downloading aria2c for Linux ($ARCH)..."',
      '      (curl -fsSL "$A_URL" -o "$TMPDIR/aria2.tar.bz2" 2>/dev/null || wget -q "$A_URL" -O "$TMPDIR/aria2.tar.bz2" 2>/dev/null || true)',
      '      if [ -f "$TMPDIR/aria2.tar.bz2" ]; then',
      '        tar -xjf "$TMPDIR/aria2.tar.bz2" -C "$TMPDIR" 2>/dev/null || true',
      '        find "$TMPDIR" -name "aria2c" -type f -exec cp -f {} "$SCRIPT_DIR/bin/aria2c" \; 2>/dev/null || true',
      '        chmod +x "$SCRIPT_DIR/bin/aria2c" 2>/dev/null || true',
      '        if [ -x "$SCRIPT_DIR/bin/aria2c" ]; then ARIA2="$SCRIPT_DIR/bin/aria2c"; fi',
      '      fi',
      '    fi',
      '  elif [ "$OS" = "Darwin" ]; then',
      '    if command -v brew >/dev/null 2>&1; then',
      '      echo "Installing aria2 via Homebrew..."',
      '      brew install aria2 2>/dev/null || true',
      '      if command -v aria2c >/dev/null 2>&1; then ARIA2=$(command -v aria2c); fi',
      '    fi',
      '  fi',
      'fi',
      '',
      'cat > "$LIST_FILE" << "EOF_PARTS"'
    ) + ($PartsLines -join "`n") + @(
      'EOF_PARTS',
      '',
      'if [ -n "$ARIA2" ] && "$ARIA2" --version >/dev/null 2>&1; then',
      '  echo "Starting download of parts with aria2c"',
      '  "$ARIA2" --input-file="$LIST_FILE" --dir="$LAUNCH_DIR" --auto-file-renaming=false --allow-overwrite=true --continue=true --max-concurrent-downloads=16 --split=16 --min-split-size=1M --check-integrity=true --console-log-level=warn --summary-interval=30 --file-allocation=none',
      'else',
      '  echo "aria2c unavailable; downloading parts with curl/wget..."',
      '  while read -r line; do',
      '    case "$line" in',
      '      http*|https*)',
      '        url="$line"',
      '        read -r chk || true',
      '        read -r out || true',
      '        fn="${out#out=}"',
      '        fn="$(echo "$fn" | tr -d '' \r\n'')"',
      '        if [ -n "$url" ] && [ -n "$fn" ]; then',
      '          echo "Downloading $fn..."',
      '          curl -fSL "$url" -o "$LAUNCH_DIR/$fn" 2>/dev/null || wget -q "$url" -O "$LAUNCH_DIR/$fn"',
      '        fi',
      '        ;;',
      '    esac',
      '  done < "$LIST_FILE"',
      'fi',
      '',
      'firstpart=""',
      'for f in "$LAUNCH_DIR"/*.zip.001; do',
      '  if [ -f "$f" ]; then firstpart="$f"; break; fi',
      'done',
      '[ -n "$firstpart" ] || { echo "ERROR: No *.zip.001 found" >&2; exit 1; }',
      '',
      'if [ -n "$SEVEN_ZIP" ]; then',
      '  echo "Extracting ISO with 7z"',
      '  "$SEVEN_ZIP" x "$firstpart" -o"$LAUNCH_DIR" -y -bsp1 -bso0',
      'else',
      '  echo "7z binary unavailable; combining parts and extracting with unzip"',
      '  command -v unzip >/dev/null 2>&1 || { echo "ERROR: unzip not available for fallback" >&2; exit 1; }',
      '  combined_zip="$TMPDIR/combined.zip"',
      '  rm -f "$combined_zip"',
      '  part_prefix="${firstpart%???}"',
      '  parts_found=0',
      '  for part in "${part_prefix}"???; do',
      '    [ -f "$part" ] || continue',
      '    cat "$part" >> "$combined_zip"',
      '    parts_found=$((parts_found + 1))',
      '  done',
      '  [ "$parts_found" -gt 0 ] || { echo "ERROR: No zip parts found for fallback extraction" >&2; exit 1; }',
      '  unzip -o "$combined_zip" -d "$LAUNCH_DIR" >/dev/null',
      'fi',
      '',
      'iso=""',
      'for f in "$LAUNCH_DIR"/*.ISO "$LAUNCH_DIR"/*.iso; do',
      '  if [ -f "$f" ]; then iso="$f"; break; fi',
      'done',
      '[ -n "$iso" ] || { echo "ERROR: ISO not found" >&2; exit 1; }',
      '',
      'dest="$LAUNCH_DIR/$(basename "$iso")"',
      'if [ "$iso" != "$dest" ]; then',
      '  mv -f "$iso" "$dest"',
      'fi',
      'echo "ISO saved to: $(basename "$dest")"',
      '',
      'rm -rf "$TMPDIR"',
      '',
      'exit 0'
    )
    $path = Join-Path $destDir 'get-with-aria2.sh'
    $body = ($lines -join "`n")
    $body = $body -replace "`r",""
    $utf8NoBom = New-Object System.Text.UTF8Encoding($false)
    [System.IO.File]::WriteAllText($path, $body, $utf8NoBom)
}

# Main packaging flow
$pkgDir = Join-Path $DistDir "isoautodl"
New-Item -ItemType Directory -Force -Path $pkgDir | Out-Null
New-BAT -destDir $pkgDir -PartsLines $PartsLines
New-SH -destDir $pkgDir -PartsLines $PartsLines

$zipPath = Join-Path $DistDir $ZipName
if (Test-Path $zipPath) { Remove-Item $zipPath -Force }
Compress-Archive -Path (Join-Path $pkgDir '*') -DestinationPath $zipPath -Force
